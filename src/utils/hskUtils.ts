// Build a single lookup map for O(1) access
let _wordLevelMap: Map<string, number> | null = null;

function getWordLevelMap(): Map<string, number> {
  if (_wordLevelMap) return _wordLevelMap;
  _wordLevelMap = new Map();
  for (let level = 1; level <= 6; level++) {
    for (const word of HSK_DATA[level]) {
      if (!_wordLevelMap.has(word)) {
        _wordLevelMap.set(word, level);
      }
    }
  }
  return _wordLevelMap;
}

/** Get HSK level (1-6) for a Chinese word, or 0 if not in HSK list */
export function getWordHSKLevel(chinese: string): number {
  return getWordLevelMap().get(chinese) || 0;
}

/** Build a Map<chinese, hskLevel> for all words in a lyrics set */
export function buildHSKColorMap(words: { chinese: string }[]): Map<string, number> {
  const map = new Map<string, number>();
  const levelMap = getWordLevelMap();
  for (const w of words) {
    const level = levelMap.get(w.chinese);
    if (level) map.set(w.chinese, level);
  }
  return map;
}

/** Calculate average HSK level for a song's lyrics */
export function getSongDifficulty(lyrics: { words: { chinese: string }[] }[]): number {
  const levelMap = getWordLevelMap();
  let total = 0;
  let count = 0;
  for (const line of lyrics) {
    for (const word of line.words || []) {
      const level = levelMap.get(word.chinese);
      if (level) {
        total += level;
        count++;
      }
    }
  }
  return count > 0 ? Math.round(total / count) : 0;
}

/** Get difficulty label and color class */
export function getDifficultyBadge(level: number): { label: string; color: string } {
  if (level <= 2) return { label: 'Beginner', color: 'bg-green-500/20 text-green-300' };
  if (level <= 4) return { label: 'Intermediate', color: 'bg-yellow-500/20 text-yellow-300' };
  return { label: 'Advanced', color: 'bg-red-500/20 text-red-300' };
}
